// Command spritegen turns the splash PNGs exported from docs/Art/splash.aseprite
// into lizard data. It is a dev-time tool: run it from the repo root and commit
// its output.
//
//	go run ./tools/spritegen
//
// Every opaque pixel is written as its hex color literal (#rrggbb), so the
// data doesn't depend on any palette's names. Half-transparent pixels are an
// error: the splash art is hard pixels only.
package main

import (
	"fmt"
	"image"
	"image/color"
	"image/png"
	"os"
	"strings"
)

const (
	out  = "lib/ui/splash_art.liz"
	prev = "docs/Art/Previews/"
)

// The banner layout, matching the slices in docs/Art/splash.aseprite.
const (
	bannerW, bannerH = 200, 80
	logoX, logoY     = 48, 14
	lizardY          = 36 // its back hides behind the logo, belly and legs show below
	taglineY         = 56
	tagline          = "powered by lizard-script"
	taglineColor     = "#a39e88" // warm gray, readable on dark and transparent
	taglineShadow    = "#1b1a17" // 1 px down-right, keeps it readable on light desktops
	lizardFrames     = 6
	lizardStep       = 2 // px the lizard moves per frame so its planted feet don't slide
	fps              = 12
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "spritegen:", err)
		os.Exit(1)
	}
}

func run() error {
	logo, err := sprite(prev + "logo.png")
	if err != nil {
		return err
	}
	var frames []string
	for f := 0; f < lizardFrames; f++ {
		s, err := sprite(fmt.Sprintf("%slizard-%d.png", prev, f))
		if err != nil {
			return err
		}
		frames = append(frames, s)
	}

	var b strings.Builder
	b.WriteString("-~> GENERATED by `go run ./tools/spritegen` from the PNGs in docs/Art/Previews/\n")
	b.WriteString("-~> (exported from docs/Art/splash.aseprite). Do not edit by hand.\n")
	b.WriteString("-~> Each sprite is {\"size\": (w, h), \"runs\": [[y, x0, x1, color], ...]}:\n")
	b.WriteString("-~> y counts from the sprite's top, x0 is inclusive, x1 exclusive, and\n")
	b.WriteString("-~> color is a COLOR literal. Draw each run with fb.span (or group them\n")
	b.WriteString("-~> by color for fb.spans). The lizard faces right and walks left to right:\n")
	b.WriteString("-~> show frame (n % 6) and move it \"lizard_step\" px each frame, wrapping\n")
	b.WriteString("-~> around the banner. Draw order: lizard, logo, tagline.\n")
	b.WriteString("let splash_art = {\n")
	fmt.Fprintf(&b, "  \"banner\": {\"size\": (%d, %d), \"logo_at\": (%d, %d), \"lizard_y\": %d, \"tagline_y\": %d, \"tagline\": %q, \"tagline_color\": %s, \"tagline_shadow\": %s},\n",
		bannerW, bannerH, logoX, logoY, lizardY, taglineY, tagline, taglineColor, taglineShadow)
	fmt.Fprintf(&b, "  \"fps\": %d,\n  \"lizard_step\": %d,\n", fps, lizardStep)
	fmt.Fprintf(&b, "  \"logo\": %s,\n", logo)
	b.WriteString("  \"lizard\": [\n")
	for i, f := range frames {
		sep := ","
		if i == len(frames)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "    %s%s\n", f, sep)
	}
	b.WriteString("  ]\n}\n")

	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Println("wrote", out)
	return nil
}

// sprite reads one PNG and writes it as a lizard sprite map.
func sprite(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	img, err := png.Decode(f)
	if err != nil {
		return "", fmt.Errorf("%s: %v", path, err)
	}
	rs, err := runs(img)
	if err != nil {
		return "", fmt.Errorf("%s: %v", path, err)
	}
	r := img.Bounds()
	return fmt.Sprintf("{\"size\": (%d, %d), \"runs\": [%s]}", r.Dx(), r.Dy(), strings.Join(rs, ", ")), nil
}

// runs turns an image into [y, x0, x1, "color"] runs of same-colored opaque
// pixels, row by row. Transparent pixels are skipped.
func runs(img image.Image) ([]string, error) {
	r := img.Bounds()
	var rs []string
	for y := 0; y < r.Dy(); y++ {
		x := 0
		for x < r.Dx() {
			name, ok, err := colorName(img, r.Min.X+x, r.Min.Y+y)
			if err != nil {
				return nil, fmt.Errorf("pixel (%d, %d): %v", x, y, err)
			}
			if !ok {
				x++
				continue
			}
			start := x
			for x < r.Dx() {
				n, ok2, _ := colorName(img, r.Min.X+x, r.Min.Y+y)
				if !ok2 || n != name {
					break
				}
				x++
			}
			rs = append(rs, fmt.Sprintf("[%d, %d, %d, %s]", y, start, x, name))
		}
	}
	return rs, nil
}

// colorName gives the pixel's color as a lizard literal like #3fa34d; ok is
// false for a transparent pixel. A half-transparent pixel is an error.
func colorName(img image.Image, x, y int) (name string, ok bool, err error) {
	c := color.NRGBAModel.Convert(img.At(x, y)).(color.NRGBA)
	if c.A == 0 {
		return "", false, nil
	}
	if c.A != 0xff {
		return "", false, fmt.Errorf("half-transparent pixel; the splash art is hard pixels only")
	}
	return fmt.Sprintf("#%02x%02x%02x", c.R, c.G, c.B), true, nil
}
