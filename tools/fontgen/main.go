// Command fontgen turns the basicfont 7x13 face into lizard data. It is a
// dev-time tool: run it from the repo root and commit its output.
//
//	go run ./tools/fontgen
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"golang.org/x/image/font/basicfont"
)

const out = "lib/gfx/font_data.liz"

func main() {
	face := basicfont.Face7x13
	h := face.Ascent + face.Descent

	var b strings.Builder
	b.WriteString("-~> GENERATED by `go run ./tools/fontgen`. Do not edit by hand.\n")
	b.WriteString("-~> Source: golang.org/x/image/font/basicfont Face7x13 (see FONT_LICENSE) for\n")
	b.WriteString("-~> ASCII; Latin-1 letters are composed from it plus pixel accents, and a few\n")
	b.WriteString("-~> symbols are drawn by hand (see tools/fontgen/latin.go).\n")
	b.WriteString("-~> Each glyph is a list of [y, x0, x1] runs of set pixels: y counts from the\n")
	b.WriteString("-~> glyph's top, x0 is inclusive, x1 exclusive. \"fallback\" is the hollow box\n")
	b.WriteString("-~> for any character the font lacks.\n")
	fmt.Fprintf(&b, "let font_data = {\"width\": %d, \"height\": %d, \"ascent\": %d, \"glyphs\": {\n", face.Advance, h, face.Ascent)

	// ASCII straight from the face.
	ascii := map[rune]glyph{}
	var keys []rune
	for r := rune(32); r <= 126; r++ {
		top := int(r-32) * h
		var g glyph
		for y := 0; y < h; y++ {
			for x := 0; x < face.Width; x++ {
				g[y][x] = set(face, x, top+y)
			}
		}
		ascii[r] = g
		keys = append(keys, r)
	}
	all := latin(ascii)
	for r, g := range ascii {
		all[r] = g
	}
	for r := range all {
		if r > 126 {
			keys = append(keys, r)
		}
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	for _, r := range keys {
		fmt.Fprintf(&b, "  %s: %s,\n", quote(r), runs(all[r]))
	}
	fmt.Fprintf(&b, "  \"fallback\": %s\n", runs(fallbackBox()))
	b.WriteString("}}\n")

	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("wrote", out)
}

// runs turns a glyph into the lizard list of [y, x0, x1] runs.
func runs(g glyph) string {
	var rs []string
	for y := 0; y < len(g); y++ {
		x := 0
		for x < len(g[y]) {
			if !g[y][x] {
				x++
				continue
			}
			start := x
			for x < len(g[y]) && g[y][x] {
				x++
			}
			rs = append(rs, fmt.Sprintf("[%d, %d, %d]", y, start, x))
		}
	}
	return "[" + strings.Join(rs, ", ") + "]"
}

// set reports whether the mask pixel at (x, y) is on.
func set(face *basicfont.Face, x, y int) bool {
	_, _, _, a := face.Mask.At(x, y).RGBA()
	return a > 0
}

// quote writes a rune as a lizard string literal.
func quote(r rune) string {
	if r == '"' || r == '\\' {
		return `"\` + string(r) + `"`
	}
	return `"` + string(r) + `"`
}
