// Command fontgen turns the basicfont 7x13 face into lizard data. It is a
// dev-time tool: run it from the repo root and commit its output.
//
//	go run ./tools/fontgen
package main

import (
	"fmt"
	"os"
	"strings"

	"golang.org/x/image/font/basicfont"
)

const out = "lib/gfx/font_data.liz"

func main() {
	face := basicfont.Face7x13
	h := face.Ascent + face.Descent

	var b strings.Builder
	b.WriteString("-~> GENERATED by `go run ./tools/fontgen`. Do not edit by hand.\n")
	b.WriteString("-~> Source: golang.org/x/image/font/basicfont Face7x13 (see FONT_LICENSE).\n")
	b.WriteString("-~> Each glyph is a list of [y, x0, x1] runs of set pixels: y counts from the\n")
	b.WriteString("-~> glyph's top, x0 is inclusive, x1 exclusive.\n")
	fmt.Fprintf(&b, "let font_data = {\"width\": %d, \"height\": %d, \"ascent\": %d, \"glyphs\": {\n", face.Advance, h, face.Ascent)

	for r := rune(32); r <= 126; r++ {
		top := int(r-32) * h
		var runs []string
		for y := 0; y < h; y++ {
			x := 0
			for x < face.Width {
				if !set(face, x, top+y) {
					x++
					continue
				}
				start := x
				for x < face.Width && set(face, x, top+y) {
					x++
				}
				runs = append(runs, fmt.Sprintf("[%d, %d, %d]", y, start, x))
			}
		}
		sep := ","
		if r == 126 {
			sep = ""
		}
		fmt.Fprintf(&b, "  %s: [%s]%s\n", quote(r), strings.Join(runs, ", "), sep)
	}
	b.WriteString("}}\n")

	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("wrote", out)
}

// set reports whether the mask pixel at (x, y) is on.
func set(face *basicfont.Face, x, y int) bool {
	_, _, _, a := face.Mask.At(x, y).RGBA()
	return a > 0
}

// quote writes a rune as a lizard string literal.
func quote(r rune) string {
	if r == '"' || r == '\\' {
		return `"\` + string(r) + `"`
	}
	return `"` + string(r) + `"`
}
